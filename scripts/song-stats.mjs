// Refreshes src/content/songStats.ts, the numbers behind the correlation game.
// Run it after adding songs to src/content/playlist.ts:  npm run song-stats
//
// Audio features (energy, tempo, loudness…) come from ReccoBeats, looked up by Spotify id.
// Release year and popularity come from Deezer, looked up by the song's ISRC code.
// Both are free and need no keys. Songs neither service knows are left out of the game.
import fs from 'node:fs';

const PLAYLIST = 'src/content/playlist.ts';
const OUT = 'src/content/songStats.ts';

const ids = [...fs.readFileSync(PLAYLIST, 'utf8').matchAll(/id: "([A-Za-z0-9]{22})"/g)].map((m) => m[1]);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function getJson(url) {
	for (let tries = 0; tries < 3; tries++) {
		const res = await fetch(url);
		if (res.ok) return res.json();
		await sleep(1500);
	}
	return null;
}

const features = {};
for (let i = 0; i < ids.length; i += 40) {
	const batch = ids.slice(i, i + 40);
	const json = await getJson(`https://api.reccobeats.com/v1/audio-features?ids=${batch.join(',')}`);
	for (const f of json?.content ?? []) features[f.href.split('/track/')[1]] = f;
	await sleep(500);
}

const round = (n, places) => Math.round(n * 10 ** places) / 10 ** places;
const lines = [];
for (const id of ids) {
	const f = features[id];
	if (!f) continue;
	const deezer = f.isrc ? await getJson(`https://api.deezer.com/track/isrc:${f.isrc}`) : null;
	await sleep(150);
	const found = deezer && !deezer.error;
	const stats = {
		energy: round(f.energy, 3),
		danceability: round(f.danceability, 3),
		valence: round(f.valence, 3),
		tempo: Math.round(f.tempo),
		loudness: round(f.loudness, 1),
		acousticness: round(f.acousticness, 3),
		...(found && deezer.release_date ? { year: Number(deezer.release_date.slice(0, 4)) } : {}),
		...(found && deezer.rank ? { rank: deezer.rank } : {}),
	};
	const fields = Object.entries(stats)
		.map(([k, v]) => `${k}: ${v}`)
		.join(', ');
	lines.push(`\t${JSON.stringify(id)}: { ${fields} },`);
}

fs.writeFileSync(
	OUT,
	`/*
 * Numbers behind the correlation game, one line per song in playlist.ts (keyed by Spotify id).
 * Generated by \`npm run song-stats\`; re-run it after adding songs instead of editing by hand.
 *
 * energy, danceability, valence (how happy it sounds), acousticness: 0 to 1, from ReccoBeats
 * tempo: beats per minute · loudness: average dB (closer to 0 is louder), from ReccoBeats
 * year: release year · rank: Deezer's popularity score (higher is more popular), from Deezer
 */

export type SongStats = {
	energy: number;
	danceability: number;
	valence: number;
	tempo: number;
	loudness: number;
	acousticness: number;
	year?: number;
	rank?: number;
};

// prettier-ignore
export const songStats: Record<string, SongStats> = {
${lines.join('\n')}
};
`,
);
console.log(`${lines.length} of ${ids.length} songs have stats`);
